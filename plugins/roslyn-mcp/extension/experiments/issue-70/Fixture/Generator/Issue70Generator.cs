using System;
using System.IO;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Issue70Fixture;

[Generator(LanguageNames.CSharp)]
public sealed class Issue70Generator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var markerProvider = context.AdditionalTextsProvider
			.Where(static file => string.Equals(Path.GetFileName(file.Path), "marker.txt", StringComparison.OrdinalIgnoreCase))
			.Select(static (file, ct) => file.GetText(ct)?.ToString()?.Trim() ?? "A")
			.Collect();

		context.RegisterSourceOutput(markerProvider, static (spc, markers) =>
		{
			var marker = markers.FirstOrDefault() ?? "A";

			// Both emitted names appear literally; the input marker selects between them.
			var memberName = string.Equals(marker, "B", StringComparison.OrdinalIgnoreCase)
				? "MemberB"
				: "MemberA";

			var source = $@"// <auto-generated />
namespace Issue70Fixture
{{
	public static class GeneratedControl {{ public const string Value = ""Stable""; }}
	public static class GeneratedApi
	{{
		public static string {memberName} => ""{memberName}"";
	}}
}}
";
			spc.AddSource("GeneratedApi.g.cs", SourceText.From(source, System.Text.Encoding.UTF8));
		});
	}
}
